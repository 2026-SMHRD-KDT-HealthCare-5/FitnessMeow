/**
 * server.js — HTTP 서버 진입점
 *
 * 목차:
 *   1. 환경변수 로드   — dotenv 로 .env 파일 파싱
 *   2. 앱 임포트       — app.js 에서 구성된 Express 앱 가져오기
 *   3. 포트 설정       — 환경변수 PORT 또는 기본값 3001
 *   4. 서버 시작       — app.listen 으로 HTTP 서버 구동
 */

// ══════════════════════════════════════
// 1. 환경변수 로드
//    .env 파일을 읽어 process.env 에 주입 (가장 먼저 실행되어야 함)
// ══════════════════════════════════════
require('dotenv').config();

// ══════════════════════════════════════
// 2. 앱 임포트
//    미들웨어·라우터가 모두 등록된 Express 앱 인스턴스
// ══════════════════════════════════════
const app = require('./app');

// ══════════════════════════════════════
// 3. 포트 설정
//    환경변수 PORT 가 있으면 사용, 없으면 3001 기본값
// ══════════════════════════════════════
const PORT = process.env.PORT || 3001;

// ══════════════════════════════════════
// 4. 서버 시작
//    지정된 포트에서 HTTP 요청 수신 대기
// ══════════════════════════════════════
app.listen(PORT, () => {
  console.log(`✅ 서버 실행: http://localhost:${PORT}`);
});
